# repository_intelligence/manifest/manifest_builder.py

import os
import hashlib
from datetime import datetime
from typing import Dict, List, Set, Optional

from repository_intelligence.manifest.models import FileRecord, ModuleRecord, RepositoryManifest

IGNORE_DIRS: Set[str] = {
    ".git",
    ".agent",
    "node_modules",
    "target",
    "dist",
    "build",
    "__pycache__",
    "out",
    "bin",
    "obj",
    "venv",
    ".venv"
}

IGNORE_EXTENSIONS: Set[str] = {
    ".class",
    ".log",
    ".dumpstream",
    ".min.js",
    ".map",
    ".xml",
    ".png",
    ".jpg",
    ".jpeg",
    ".gif",
    ".ico",
    ".svg",
    ".DS_Store"
}

def detect_language(path: str) -> str:
    ext = os.path.splitext(path)[1].lower()
    mapping = {
        ".java": "java",
        ".py": "python",
        ".ts": "typescript",
        ".tsx": "typescript",
        ".js": "javascript",
        ".jsx": "javascript",
        ".css": "css",
        ".scss": "css",
        ".html": "html",
        ".json": "json",
        ".md": "markdown",
        ".sh": "bash",
        ".yml": "yaml",
        ".yaml": "yaml",
        ".properties": "properties"
    }
    return mapping.get(ext, "unknown")

def detect_module(path: str) -> str:
    parts = path.split(os.sep)
    if len(parts) > 1:
        first_dir = parts[0]
        if first_dir in ("backend", "frontend", "infra", "repository_intelligence"):
            return first_dir
    return "root"

def detect_file_type(path: str, ext: str) -> str:
    p_lower = path.lower()
    if "test" in p_lower or "/tests/" in p_lower or "/src/test/" in p_lower:
        return "test"
    if ext in (".json", ".yaml", ".yml", ".properties", ".xml"):
        return "config"
    if ext in (".md", ".txt"):
        return "meta"
    return "source"

def get_file_hash_and_size(abs_path: str) -> tuple[str, int]:
    try:
        with open(abs_path, "rb") as f:
            content = f.read()
            h = hashlib.sha256(content).hexdigest()
            return h, len(content)
    except Exception:
        return "", 0

def is_generated_source(abs_path: str) -> bool:
    # 1. MapStruct generated mapper check
    name = os.path.basename(abs_path)
    if (name.endswith("MapperImpl.java") or name.endswith("Impl.java")) and "Mapper" in name:
        return True
    
    # 2. Inspect file header for processor signature
    try:
        with open(abs_path, "r", encoding="utf-8", errors="ignore") as f:
            for _ in range(30):
                line = f.readline()
                if not line:
                    break
                if "@Generated" in line or "Generated by" in line:
                    return True
    except Exception:
        pass
        
    return False

class ManifestBuilder:
    @staticmethod
    def build(repo_root: str) -> RepositoryManifest:
        manifest = RepositoryManifest()
        
        # Initialize modules
        for mod_name in ("backend", "frontend", "infra", "repository_intelligence", "root"):
            root_path = "" if mod_name == "root" else mod_name
            manifest.modules[mod_name] = ModuleRecord(
                name=mod_name,
                root_path=root_path,
                language="java" if mod_name == "backend" else "typescript" if mod_name == "frontend" else "python"
            )
            
        # Dependencies mapping
        manifest.modules["backend"].dependencies = ["infra"]
        manifest.modules["frontend"].dependencies = ["backend"]
        
        # Connect to DB to fetch symbol counts (if database exists)
        symbol_counts: Dict[str, int] = {}
        try:
            from repository_intelligence.db.connection import SessionLocal
            from repository_intelligence.models.symbol import Symbol
            from repository_intelligence.models.file import File
            db = SessionLocal()
            try:
                from sqlalchemy import func
                query_res = db.query(File.path, func.count(Symbol.id))\
                              .join(Symbol, Symbol.file_id == File.id)\
                              .group_by(File.path).all()
                for fp, count in query_res:
                    symbol_counts[fp] = count
            except Exception as dberr:
                print(f"[ManifestBuilder] Warning querying database symbols: {dberr}")
            finally:
                db.close()
        except Exception:
            pass

        # Scan repo files
        for root, dirs, files in os.walk(repo_root):
            # Prune directories in place
            dirs[:] = [d for d in dirs if d not in IGNORE_DIRS]
            
            for file in files:
                ext = os.path.splitext(file)[1]
                if ext in IGNORE_EXTENSIONS:
                    continue
                    
                abs_path = os.path.join(root, file)
                rel_path = os.path.relpath(abs_path, repo_root)
                
                # Check for duplicate generated sources
                if is_generated_source(abs_path):
                    continue
                    
                lang = detect_language(rel_path)
                module = detect_module(rel_path)
                file_type = detect_file_type(rel_path, ext.lower())
                h, size = get_file_hash_and_size(abs_path)
                
                # Determine symbol count
                sym_count = symbol_counts.get(rel_path, 0)
                
                record = FileRecord(
                    path=rel_path,
                    language=lang,
                    module=module,
                    file_type=file_type,
                    symbol_count=sym_count,
                    hash=h,
                    size_bytes=size,
                    indexed_at=datetime.utcnow().isoformat()
                )
                
                manifest.files_by_path[rel_path] = record
                
                # Indices
                manifest.files_by_module.setdefault(module, []).append(record)
                manifest.files_by_language.setdefault(lang, []).append(record)
                
        return manifest
