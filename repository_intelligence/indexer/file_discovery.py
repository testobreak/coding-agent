def is_generated_source(filepath: Path) -> bool:
    """Check if the file is a tool-generated source representation (e.g. MapStruct, lombok, etc.)."""
    name = filepath.name
    # MapStruct generated files
    if name.endswith("MapperImpl.java") or (name.endswith("Impl.java") and "Mapper" in name):
        return True

    # Read the first 30 lines to check for @Generated or standard generator markers
    if filepath.suffix.lower() == ".java":
        try:
            if filepath.exists():
                with open(filepath, "r", encoding="utf-8", errors="ignore") as f:
                    head = [f.readline() for _ in range(30)]
                    content = "".join(head)
                    if "@Generated" in content or "Generated by" in content or "generated by MapStruct" in content:
                        return True
        except Exception:
            pass

    return False


def is_file_discoverable(filepath: Path, root: Path) -> bool:
    """Return True if the filepath is eligible for indexing."""
    from repository_intelligence.indexer.file_classifier import FileClassifier
    decision = FileClassifier.classify(filepath, root)
    return decision.include


def discover_files(root_path: str):
    """Walk the repository efficiently, pruning ignored dirs at every level.

    Two layers of protection:
    1. `os.walk` topdown pruning — prevents descending into ignored dirs.
    2. Path-segment filter — catches any file that somehow slips through
       (e.g. symlinked build dirs, unusual nesting).
    """
    root = Path(root_path).resolve()

    for dirpath, dirnames, filenames in os.walk(str(root), topdown=True):
        # ── Layer 1: prune ignored dirs in-place ──────────────────────
        dirnames[:] = [
            d for d in dirnames
            if d not in IGNORED_DIR_NAMES and not d.startswith(".")
        ]

        for filename in filenames:
            filepath = Path(dirpath) / filename
            if is_file_discoverable(filepath, root):
                yield filepath