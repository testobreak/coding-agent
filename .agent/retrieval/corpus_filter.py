# retrieval/corpus_filter.py
#
# Single source-of-truth for what file paths are eligible for retrieval.
#
# Used by:
#   - retriever._load_chunks_from_db   (in-memory BM25 + SymbolIndex load)
#   - retrieval_pipeline.retrieve      (runtime broad-recall + lexical fast-path)
#   - corpus_cleanup.py                (one-time DB eviction)
#
# Rule: a file is eligible ONLY if it is a genuine source file in the
# application, NOT a build artifact, agent internal, or generated output.

import re
from pathlib import Path
from typing import FrozenSet

# ---------------------------------------------------------------------------
# Directory segments that disqualify any file whose path contains them
# ---------------------------------------------------------------------------
BLOCKED_PATH_SEGMENTS: FrozenSet[str] = frozenset({
    # Agent internals — never expose agent task state to retrieval
    ".agent",
    "repository_intelligence",
    "tasks",          # .agent/tasks/*.json

    # Maven / Gradle / Java build output
    "target",
    "build",
    "classes",
    "generated",
    "generated-sources",
    "generated-test-sources",
    "apt-generated",
    ".gradle",
    ".mvn",

    # JS / Frontend bundler output
    "dist",
    "out",
    ".next",
    ".nuxt",
    ".turbo",
    "storybook-static",

    # Binary / native output
    "bin",
    "obj",

    # Python caches
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
    ".cache",

    # Node
    "node_modules",

    # Coverage / reporting
    "coverage",
    ".nyc_output",
    "htmlcov",

    # IDE config dirs
    ".idea",
    ".vscode",
    ".github",
})

# ---------------------------------------------------------------------------
# Extension blocklist — binary / compiled files that can sneak through
# ---------------------------------------------------------------------------
BLOCKED_EXTENSIONS: FrozenSet[str] = frozenset({
    ".class", ".jar", ".war", ".ear", ".nar",
    ".pyc", ".pyo", ".pyd",
    ".so", ".dll", ".dylib", ".a", ".lib", ".o", ".obj",
    ".zip", ".tar", ".gz", ".bz2", ".xz", ".rar",
    ".map",                        # source-map / minified-bundle side-files
    ".png", ".jpg", ".jpeg", ".gif", ".webp", ".svg", ".ico",
    ".woff", ".woff2", ".ttf", ".eot",
    ".pdf", ".docx", ".xlsx",
    ".lock",                       # package-lock.json, yarn.lock, Pipfile.lock
    ".log",
    ".xml",
    ".dumpstream",
})

# ---------------------------------------------------------------------------
# Filename patterns that are never indexable regardless of extension
# ---------------------------------------------------------------------------
_BLOCKED_FILENAME_RE = re.compile(
    r"""
    (?xi)
    (
        # Minified bundles (e.g. chunk.abc123.js, vendor.min.js)
        \.[a-f0-9]{8,}\.(js|css)$
        |\.min\.(js|css)$
        # Compiled/generated JS inside dist
        |\.bundle\.(js|css)$
        # Lock / manifest files
        |package-lock\.json$
        |yarn\.lock$
        |pnpm-lock\.yaml$
        |Pipfile\.lock$
        |composer\.lock$
        |Gemfile\.lock$
        # Build receipts
        |\.buildinfo$
        |MANIFEST\.MF$
    )
    """,
    re.VERBOSE,
)

# ---------------------------------------------------------------------------
# Paths whose JSON is agent state rather than config — exact segment checks
# ---------------------------------------------------------------------------
_AGENT_JSON_SEGMENT_RE = re.compile(
    r"""
    (?xi)
    (
        /\.agent/           # anything inside .agent/
        |/tasks/            # .agent/tasks/*.json
        |/checkpoints?/     # checkpoint state files
        |/backups?/         # task backups
    )
    """,
    re.VERBOSE,
)


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def is_generated_source(file_path: str) -> bool:
    """Check if the file path is a tool-generated source representation (e.g. MapStruct, lombok, etc.)."""
    basename = Path(file_path).name
    # MapStruct generated files
    if basename.endswith("MapperImpl.java") or (basename.endswith("Impl.java") and "Mapper" in basename):
        return True

    # Read the first 30 lines to check for @Generated or standard generator markers
    if Path(file_path).suffix.lower() == ".java":
        try:
            p = Path(file_path)
            if not p.is_absolute():
                import os
                p = Path(os.getcwd()) / p
            if p.exists():
                with open(p, "r", encoding="utf-8", errors="ignore") as f:
                    head = [f.readline() for _ in range(30)]
                    content = "".join(head)
                    if "@Generated" in content or "Generated by" in content or "generated by MapStruct" in content:
                        return True
        except Exception:
            pass

    return False


def is_corpus_eligible(file_path: str) -> bool:
    """Return True only if *file_path* is a genuine source file that should
    participate in retrieval.

    Three rejection rules (any one is sufficient to reject):
    1. Path contains a blocked directory segment.
    2. File extension is in the blocklist.
    3. Filename matches a blocked pattern (minified bundles, lock files, etc.).
    4. File is a generated source implementation.
    """
    if not file_path:
        return False

    # Normalise separators
    normalised = file_path.replace("\\", "/")

    # ── Rule 1: blocked path segments ─────────────────────────────────────
    parts = Path(normalised).parts
    for part in parts:
        if part in BLOCKED_PATH_SEGMENTS:
            return False

    # ── Rule 1b: agent JSON via regex (catches mixed-separator paths) ──────
    if _AGENT_JSON_SEGMENT_RE.search("/" + normalised):
        return False

    # ── Rule 2: blocked extension ──────────────────────────────────────────
    ext = Path(normalised).suffix.lower()
    if ext in BLOCKED_EXTENSIONS:
        return False

    # ── Rule 3: blocked filename pattern ──────────────────────────────────
    basename = Path(normalised).name
    if _BLOCKED_FILENAME_RE.search(basename):
        return False

    # ── Rule 4: block generated source files (P1 - duplicate representations)
    if is_generated_source(normalised):
        return False

    return True


def filter_chunks(chunks: list) -> list:
    """Filter a list of chunk dicts, keeping only corpus-eligible ones.

    Chunks must have a ``file`` key with the file path.
    """
    return [c for c in chunks if is_corpus_eligible(c.get("file", ""))]
